public class StudentGrade2_2_{ 
    public static void main(String []args){
        int grade = 39;

        if (grade >= 90)
            System.out.println("A");
        else if(grade >= 70)
            System.out.println("B");
        else if(grade >= 50)
            System.out.println("C");
        else if(grade >= 40)
            System.out.println("D");
        else
            System.out.println("F");
    }
}